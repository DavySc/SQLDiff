//! T-SQL `OUTPUT … INTO` compared with PostgreSQL `WITH o AS (… RETURNING …)
//! INSERT INTO … SELECT … FROM o`: the data change, and the rows it writes
//! to the OUTPUT table read from the row before (`deleted`, `old`) or after
//! (`inserted`, `new`) the change.

use sqldiff_core::{diff, Artifact, Dialect, Options, Report, Verdict};

const T: Dialect = Dialect::Tsql;
const P: Dialect = Dialect::Postgres;

const DDL: &str = "
CREATE TABLE item (item_id integer PRIMARY KEY, name varchar(100) NOT NULL, qty integer);
CREATE TABLE item_log (item_id integer, old_qty integer, new_qty integer);
CREATE TABLE item_log2 (n integer GENERATED BY DEFAULT AS IDENTITY, item_id integer);
";

fn run(a: &str, b: &str) -> Report {
    let opts = Options {
        catalog_a: vec![Artifact::new("catalog.sql", T, DDL)],
        catalog_b: vec![Artifact::new("catalog.sql", P, DDL)],
        ..Options::default()
    };
    diff(
        &Artifact::new("a.sql", T, a),
        &Artifact::new("b.sql", P, b),
        &opts,
    )
}

fn ts(stmt: &str) -> String {
    format!("CREATE PROCEDURE dbo.p @id int, @q int AS\nBEGIN\n  {stmt};\nEND\n")
}

fn pg(stmt: &str) -> String {
    format!("CREATE OR REPLACE PROCEDURE p(p_id integer, p_q integer)\nLANGUAGE plpgsql\nAS $$\nBEGIN\n  {stmt};\nEND;\n$$;\n")
}

fn why(r: &Report) -> String {
    format!("{:#?}\n{:#?}", r.findings, r.unknown_reasons)
}

fn equal(a: &str, b: &str) -> Report {
    let r = run(&ts(a), &pg(b));
    assert!(
        matches!(r.verdict(), Verdict::Equal | Verdict::EqualUnderAssumptions),
        "{a}\n{b}\n{}",
        why(&r)
    );
    r
}

fn not_equal(a: &str, b: &str, what: &str) {
    let r = run(&ts(a), &pg(b));
    if std::env::var("SHOW").is_ok() {
        eprintln!(
            "== {what}: {:?} {:?} {:?}",
            r.verdict(),
            r.findings
                .iter()
                .map(|f| (&f.rule, &f.witness))
                .collect::<Vec<_>>(),
            r.unknown_reasons
        );
    }
    assert!(
        !matches!(r.verdict(), Verdict::Equal | Verdict::EqualUnderAssumptions),
        "{what}: {}",
        why(&r)
    );
}

#[test]
fn update_output_into_equals_returning_old_and_new() {
    let r = equal(
        "UPDATE dbo.item SET qty = @q OUTPUT inserted.item_id, deleted.qty, inserted.qty INTO dbo.item_log (item_id, old_qty, new_qty) WHERE item_id = @id",
        "WITH sqldiff_output AS (UPDATE item SET qty = p_q WHERE item_id = p_id RETURNING new.item_id AS item_id, old.qty AS old_qty, new.qty AS new_qty) INSERT INTO item_log (item_id, old_qty, new_qty) SELECT item_id, old_qty, new_qty FROM sqldiff_output",
    );
    assert!(r
        .assumptions
        .iter()
        .any(|a| a.id == "ASM-OUTPUT-INTO-TARGET"));
    assert!(!r.assumptions.iter().any(|a| a.id == "ASM-OUTPUT-ROW-ORDER"));
    // A bare column of an UPDATE's RETURNING is the new row.
    equal(
        "UPDATE dbo.item SET qty = @q OUTPUT inserted.item_id, deleted.qty, inserted.qty INTO dbo.item_log (item_id, old_qty, new_qty) WHERE item_id = @id",
        "WITH o AS (UPDATE item SET qty = p_q WHERE item_id = p_id RETURNING item_id, old.qty AS old_qty, item.qty AS new_qty) INSERT INTO item_log (item_id, old_qty, new_qty) SELECT item_id, old_qty, new_qty FROM o",
    );
}

#[test]
fn old_and_new_rows_are_not_confused() {
    not_equal(
        "UPDATE dbo.item SET qty = @q OUTPUT inserted.item_id, deleted.qty, inserted.qty INTO dbo.item_log (item_id, old_qty, new_qty) WHERE item_id = @id",
        "WITH o AS (UPDATE item SET qty = p_q WHERE item_id = p_id RETURNING item_id, new.qty AS old_qty, new.qty AS new_qty) INSERT INTO item_log (item_id, old_qty, new_qty) SELECT item_id, old_qty, new_qty FROM o",
        "deleted.qty against new.qty",
    );
    not_equal(
        "UPDATE dbo.item SET qty = @q OUTPUT inserted.item_id, deleted.qty, inserted.qty INTO dbo.item_log (item_id, old_qty, new_qty) WHERE item_id = @id",
        "WITH o AS (UPDATE item SET qty = p_q WHERE item_id = p_id RETURNING item_id, old.qty AS new_qty, new.qty AS old_qty) INSERT INTO item_log (item_id, new_qty, old_qty) SELECT item_id, new_qty, old_qty FROM o",
        "columns swapped",
    );
    not_equal(
        "UPDATE dbo.item SET qty = @q OUTPUT inserted.item_id INTO dbo.item_log (item_id) WHERE item_id = @id",
        "UPDATE item SET qty = p_q WHERE item_id = p_id",
        "OUTPUT INTO dropped",
    );
    not_equal(
        "UPDATE dbo.item SET qty = @q OUTPUT inserted.item_id INTO dbo.item_log (item_id) WHERE item_id = @id",
        "WITH o AS (UPDATE item SET qty = p_q WHERE item_id = p_id RETURNING item_id) INSERT INTO item_log2 (item_id) SELECT item_id FROM o",
        "another OUTPUT table",
    );
}

#[test]
fn delete_output_into_reads_the_old_row() {
    equal(
        "DELETE FROM dbo.item OUTPUT deleted.item_id, deleted.qty INTO dbo.item_log (item_id, old_qty) WHERE qty = 0",
        "WITH o AS (DELETE FROM item WHERE qty = 0 RETURNING item_id, old.qty AS old_qty) INSERT INTO item_log (item_id, old_qty) SELECT item_id, old_qty FROM o",
    );
    // inserted is not a row of a DELETE (T-SQL rejects it).
    not_equal(
        "DELETE FROM dbo.item OUTPUT inserted.item_id INTO dbo.item_log (item_id) WHERE qty = 0",
        "WITH o AS (DELETE FROM item WHERE qty = 0 RETURNING item_id) INSERT INTO item_log (item_id) SELECT item_id FROM o",
        "inserted in a DELETE",
    );
}

#[test]
fn insert_output_into_with_variables_and_generated_values() {
    let r = equal(
        "INSERT INTO dbo.item (item_id, name) OUTPUT inserted.item_id, @q INTO dbo.item_log2 (item_id, n) VALUES (@id, N'x')",
        "WITH o AS (INSERT INTO item (item_id, name) VALUES (p_id, 'x') RETURNING item_id, p_q AS n) INSERT INTO item_log2 (item_id, n) SELECT item_id, n FROM o",
    );
    assert!(!r.assumptions.iter().any(|a| a.id == "ASM-OUTPUT-ROW-ORDER"));
    let r = equal(
        "INSERT INTO dbo.item (item_id, name) OUTPUT inserted.item_id INTO dbo.item_log2 (item_id) SELECT item_id + 1000, name FROM dbo.item WHERE qty = 0",
        "WITH o AS (INSERT INTO item (item_id, name) SELECT item_id + 1000, name FROM item WHERE qty = 0 RETURNING item_id) INSERT INTO item_log2 (item_id) SELECT item_id FROM o",
    );
    assert!(
        r.assumptions.iter().any(|a| a.id == "ASM-OUTPUT-ROW-ORDER"),
        "item_log2.n is an identity the rows get in some order: {}",
        why(&r)
    );
}

#[test]
fn returned_names_must_feed_the_insert_in_order() {
    not_equal(
        "UPDATE dbo.item SET qty = @q OUTPUT deleted.qty, inserted.qty INTO dbo.item_log (old_qty, new_qty) WHERE item_id = @id",
        "WITH o AS (UPDATE item SET qty = p_q WHERE item_id = p_id RETURNING old.qty AS a, new.qty AS b) INSERT INTO item_log (old_qty, new_qty) SELECT b, a FROM o",
        "the INSERT reads the returned columns out of order",
    );
}

/// PL/pgSQL raises "column reference is ambiguous" for a bare RETURNING
/// name that is also a variable.
#[test]
fn a_returned_name_that_is_also_a_variable_is_refused() {
    let r = run(
        "CREATE PROCEDURE dbo.p @qty int AS\nBEGIN\n  DELETE FROM dbo.item OUTPUT deleted.qty INTO dbo.item_log (old_qty) WHERE qty = @qty;\nEND\n",
        "CREATE OR REPLACE PROCEDURE p(qty integer)\nLANGUAGE plpgsql\nAS $$\nBEGIN\n  WITH o AS (DELETE FROM item WHERE item.qty = p.qty RETURNING qty AS old_qty) INSERT INTO item_log (old_qty) SELECT old_qty FROM o;\nEND;\n$$;\n",
    );
    assert!(
        !matches!(r.verdict(), Verdict::Equal | Verdict::EqualUnderAssumptions),
        "{}",
        why(&r)
    );
    assert!(
        why(&r).contains("names both a column and a variable"),
        "{}",
        why(&r)
    );
}

#[test]
fn rows_returned_to_the_caller_are_not_compared() {
    not_equal(
        "INSERT INTO dbo.item (item_id, name) OUTPUT inserted.item_id VALUES (@id, N'x')",
        "INSERT INTO item (item_id, name) VALUES (p_id, 'x')",
        "result set dropped",
    );
}

/// PostgreSQL 18 RETURNING binds `old.c` and `new.c` to the changed table.
#[test]
fn returning_old_and_new_bind_to_the_target() {
    use sqldiff_core::artifact::Analyzed;
    use sqldiff_core::bind::{self, BindInput, Resolution};
    use sqldiff_core::catalog::{ddl, CatalogView};
    let cat = ddl::load(DDL, P, "catalog.sql");
    let view = CatalogView::new(P, &[&cat]);
    let src = pg("WITH o AS (UPDATE item SET qty = p_q WHERE item_id = p_id RETURNING new.item_id AS item_id, old.qty AS old_qty) INSERT INTO item_log (item_id, old_qty) SELECT item_id, old_qty FROM o");
    let art = Artifact::new("b.sql", P, &src);
    let analyzed = Analyzed::new(&art, sqldiff_core::model::Side::B, 3);
    let bound = bind::bind(
        &analyzed,
        &BindInput {
            view: &view,
            helpers: &[],
        },
    );
    for r in &bound.refs {
        assert!(
            matches!(r.resolution, Resolution::Resolved(_)),
            "{} {:?}",
            r.name,
            r.resolution
        );
    }
}

/// `old` and `new` name the row images in RETURNING only.
#[test]
fn old_and_new_outside_returning_do_not_bind() {
    use sqldiff_core::artifact::Analyzed;
    use sqldiff_core::bind::{self, BindInput, Resolution};
    use sqldiff_core::catalog::{ddl, CatalogView};
    let cat = ddl::load(DDL, P, "catalog.sql");
    let view = CatalogView::new(P, &[&cat]);
    let src = pg("UPDATE item SET qty = p_q WHERE new.item_id = p_id RETURNING old.qty INTO p_q");
    let art = Artifact::new("b.sql", P, &src);
    let analyzed = Analyzed::new(&art, sqldiff_core::model::Side::B, 3);
    let bound = bind::bind(
        &analyzed,
        &BindInput {
            view: &view,
            helpers: &[],
        },
    );
    let r = bound
        .refs
        .iter()
        .find(|r| r.name.eq_ignore_ascii_case("new.item_id"))
        .expect("new.item_id is a reference");
    assert!(
        !matches!(r.resolution, Resolution::Resolved(_)),
        "{:?}",
        r.resolution
    );
    let r = bound
        .refs
        .iter()
        .find(|r| r.name.eq_ignore_ascii_case("old.qty"))
        .expect("old.qty is a reference");
    assert!(
        matches!(r.resolution, Resolution::Resolved(_)),
        "{:?}",
        r.resolution
    );
}
