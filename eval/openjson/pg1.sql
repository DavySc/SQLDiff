\set ON_ERROR_STOP off
create or replace function rows_of(src text) returns setof jsonb language sql as $$
 select e from jsonb_array_elements(CASE jsonb_typeof(CAST(src AS jsonb)) WHEN 'object' THEN CASE CAST(src AS jsonb) WHEN '{}' THEN '[]' ELSE jsonb_build_array(CAST(src AS jsonb)) END ELSE CAST(src AS jsonb) END) AS e $$;
select 'obj-rows', count(*) from rows_of('{"a":"x"}');
select 'arr-rows', count(*) from rows_of('[{"a":"x"},{"a":"y"}]');
select 'empty-arr', count(*) from rows_of('[]');
select 'empty-obj', count(*) from rows_of('{}');
select 'scalar', count(*) from rows_of('5');
select 'string', count(*) from rows_of('"s"');
select 'null-in', count(*) from rows_of(NULL);
select 'emptystr', count(*) from rows_of('');
select 'ws', count(*) from rows_of(' {"a":"x"} ');
select 'arr-mixed', string_agg('['||coalesce(e->>'a','')||']', ',') from rows_of('[1,{"a":"y"},"s",null,[1]]') e;
select 'arr-of-empty', count(*) from rows_of('[{}, {}]');
select 'lax-missing', coalesce(e->>'a','<null>') from rows_of('{"b":1}') e;
select 'strict-missing', jsonb_path_query_first(e, 'strict $."a"') #>> '{}' from rows_of('{"b":1}') e;
select 'strict-null', coalesce(jsonb_path_query_first(e, 'strict $."a"') #>> '{}','<null>') from rows_of('{"a":null}') e;
select 'strict-scalar-elem', jsonb_path_query_first(e, 'strict $."a"') #>> '{}' from rows_of('[1,{"a":"y"}]') e;
select 'lax-null', coalesce(e->>'a','<null>') from rows_of('{"a":null}') e;
select 'dup', e->>'a' from rows_of('{"a":"first","a":"second"}') e;
select 'trunc', CAST(e->>'a' AS varchar(5)) from rows_of('{"a":"abcdefgh"}') e;
select 'trunc-surr', CAST(e->>'a' AS varchar(2)) from rows_of('{"a":"a😀bc"}') e;
select 'num-str', e->>'a' from rows_of('{"a":1.50}') e;
select 'exp-str', e->>'a' from rows_of('{"a":1e2}') e;
select 'bool-str', e->>'a' from rows_of('{"a":true}') e;
select 'trail-sp', '['||CAST(e->>'a' AS varchar(10))||']' from rows_of('{"a":"x  "}') e;
select 'int', CAST(e->>'a' AS integer) from rows_of('{"a":12}') e;
select 'int-neg', CAST(e->>'a' AS integer) from rows_of('{"a":-12}') e;
select 'int-big', CAST(e->>'a' AS integer) from rows_of('{"a":2147483648}') e;
select 'int-frac', CAST(e->>'a' AS integer) from rows_of('{"a":12.7}') e;
select 'bigint', CAST(e->>'a' AS bigint) from rows_of('{"a":9007199254740993}') e;
select 'dec', CAST(e->>'a' AS numeric(18,2)) from rows_of('{"a":1.005}') e;
select 'dec-neg', CAST(e->>'a' AS numeric(18,2)) from rows_of('{"a":-1.005}') e;
select 'dec-half', CAST(e->>'a' AS numeric(18,2)) from rows_of('{"a":0.125}') e;
select 'dec-3', CAST(e->>'a' AS numeric(18,3)) from rows_of('{"a":2.0005}') e;
select 'dec-big', CAST(e->>'a' AS numeric(18,2)) from rows_of('{"a":1234567890123456789}') e;
select 'dec-long', CAST(e->>'a' AS numeric(18,2)) from rows_of('{"a":0.12500000000000000000000000000000000001}') e;
select 'date', CAST(e->>'a' AS date) from rows_of('{"a":"2020-01-31"}') e;
select 'date-bad', CAST(e->>'a' AS date) from rows_of('{"a":"2020-02-30"}') e;
select 'date-y1', CAST(e->>'a' AS date) from rows_of('{"a":"0001-01-01"}') e;
select 'bool-t', CAST(e->>'a' AS boolean) from rows_of('{"a":true}') e;
select 'bool-f', CAST(e->>'a' AS boolean) from rows_of('{"a":false}') e;
select 'bool-1', CAST(e->>'a' AS boolean) from rows_of('{"a":1}') e;
select 'bool-0', CAST(e->>'a' AS boolean) from rows_of('{"a":0}') e;
select 'text', length(CAST(e->>'a' AS text)) from rows_of('{"a":"' || repeat('x',9000) || '"}') e;
select 'invalid', count(*) from rows_of('{"a":}');
select 'trailing', count(*) from rows_of('[{"a":1}] x');
